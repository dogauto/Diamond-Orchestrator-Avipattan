"""Persistent Claude Code session binding for the FreeLLMAPI provider.

The controller owns session identity.  This module validates provider session
IDs, resolves per-agent Claude configuration directories, and documents the
two-phase Claude CLI invocation contract:

  * New conversation -> ``claude -p <prompt> --session-id <uuid>``.  The UUID
    is generated by the controller, passed to the CLI, and the value returned
    in the JSON output is validated against it before it is persisted.
  * Continue conversation -> ``claude -p <prompt> --resume <uuid>``.  The UUID
    is the previously persisted ``provider_session_id``.

Nothing here launches a provider or reads credentials.
"""

from __future__ import annotations

import re
from pathlib import Path

from .errors import ValidationError

_SESSION_ID_PATTERN = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\Z"
)
_AGENT_ID_PATTERN = re.compile(r"[0-9a-f]{32}\Z")


def validate_provider_session_id(value: object, name: str = "provider session id") -> str:
    """Validate that *value* is a canonical lowercase UUID."""
    if not isinstance(value, str) or _SESSION_ID_PATTERN.fullmatch(value) is None:
        raise ValidationError(f"{name} must be a UUID (8-4-4-4-12 lowercase hex)")
    return value


def optional_provider_session_id(value: object, name: str = "provider session id") -> str | None:
    if value is None:
        return None
    return validate_provider_session_id(value, name)


def validate_agent_id(value: object) -> str:
    if not isinstance(value, str) or _AGENT_ID_PATTERN.fullmatch(value) is None:
        raise ValidationError("agent_id must be 32 lowercase hexadecimal characters")
    return value


def agent_config_dir(state_dir: Path, agent_id: str) -> Path:
    """Resolve the per-agent Claude configuration directory.

    The directory lives under ``<state_dir>/agents/<agent_id>/claude-config/``
    so that concurrent agents never share Claude's session/auth state.
    """
    if not isinstance(state_dir, Path):
        raise ValidationError("state_dir must be a pathlib.Path")
    validate_agent_id(agent_id)
    directory = state_dir / "agents" / agent_id / "claude-config"
    if ".." in directory.parts:
        raise ValidationError("agent config dir must not contain traversal components")
    return directory


def assert_session_id_matches(requested: str | None, returned: object, *, what: str = "session id") -> str:
    """Validate a provider-returned session id before it is persisted.

    Returns the validated id.  Raises when the returned value is not a UUID or
    does not equal the requested id (the controller never trusts provider
    output as identity without this check).
    """
    if returned is None:
        raise ValidationError(f"provider did not return a {what}")
    validated = validate_provider_session_id(returned, what)
    if requested is not None and validated != requested:
        raise ValidationError(
            f"provider {what} {validated!r} does not match requested {requested!r}"
        )
    return validated